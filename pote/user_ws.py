class UserWS:
    "Manage Solveit-safe HTMX websocket initiators and server send handles"
    def __init__(self, app, srv): store_attr(); self.sends,self.routes = {},set()

    def url(self, path):
        "Return public websocket URL for `path`"
        return f"wss://{json.loads(os.environ['PUBLIC_DOMAINS'])[str(self.srv.port)]}{path}"

    _js='user_ws'
    async def call(self, fn, *args):
        "Call a function on the browser-side websocket helper"
        args = ', '.join(json.dumps(o) for o in args)
        return await js_eval_a(f"return {self._js}.{fn}({args})")

    async def create(self, wid, path):
        "Create browser websocket initiator for `path`"
        return await self.call('create', wid, self.url(path))
    async def cleanup(self, wid):
        "Remove browser initiator element"
        return await self.call('cleanup', wid)
    async def send_client(self, wid, data):
        "Send browser to Python via JS helper"
        return await iife_a(f"{self._js}.send({json.dumps(wid)}, {json.dumps(data)})")
    async def send(self, wid, o):
        "Send Python to browser via stored send callable"
        return await self.sends[wid](o)
    async def wait(self, wid):
        "Wait for websocket connection to be registered"
        return await wait_for_a(lambda: wid in self.sends)

    def conn(self, wid):
        "Return FastHTML connect hook storing server send callable"
        async def _conn(send): self.sends[wid] = send
        return _conn

    def disconn(self, wid):
        "Return FastHTML disconnect hook clearing server send callable"
        async def _disconn(ws): self.sends.pop(wid, None)
        return _disconn

    def add(self, wid, path, handler):
        "Register websocket route once"
        if wid not in self.routes:
            self.app.ws(path, conn=self.conn(wid), disconn=self.disconn(wid))(handler)
            self.routes.add(wid)
        return wid,path

    async def start(self, wid, path, handler, wait=True):
        "Register route, create browser initiator, and optionally wait for connection"
        await self.stop(wid)
        res = self.add(wid, path, handler)
        await self.create(wid, path)
        if wait: await self.wait(wid)
        return res

    async def stop(self, wid):
        "Remove browser initiator and forget server send callable"
        try: await self.cleanup(wid)
        finally: self.sends.pop(wid, None)


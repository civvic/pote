class UserWS:
    "Manage Solveit-safe HTMX websocket initiators and server send handles keyed by `wid`"
    _js='user_ws'
    def __init__(self, app, srv, create_ui=noop_a, cleanup_ui=noop_a): store_attr(); self.sends,self.routes = {},{}

